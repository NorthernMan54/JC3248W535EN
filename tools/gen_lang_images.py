#!/usr/bin/env python3
"""Render the "Let's Build" phrases for the starter screen into LVGL alpha images.

LVGL 8 has no text shaping, so scripts like Devanagari, Bengali, Arabic and Urdu
cannot be drawn correctly from a font at runtime. This script shapes them with
HarfBuzz (via Pillow's raqm layout) and writes 8-bit alpha masks that the UI
tints at runtime.

Requirements: Pillow built with raqm, fontconfig (fc-match) and the Noto fonts below.
Usage:        python3 tools/gen_lang_images.py
Output:       src/ui/lang_images.c and src/ui/lang_images.h
"""
import os
import subprocess

from PIL import Image, ImageDraw, ImageFont, features

SIZE_PX = 24
WEIGHT = 400
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "src", "ui")

# (C identifier, English label, fontconfig family, phrase), most spoken languages first.
PHRASES = [
    ("zh", "Mandarin", "Noto Sans CJK SC", "一起来建造吧"),
    ("hi", "Hindi", "Noto Sans Devanagari", "चलो बनाते हैं"),
    ("es", "Spanish", "Noto Sans", "¡Construyamos!"),
    ("ar", "Arabic", "Noto Naskh Arabic", "هيا نبني"),
    ("fr", "French", "Noto Sans", "Construisons !"),
    ("bn", "Bengali", "Noto Sans Bengali", "চলো বানাই"),
    ("pt", "Portuguese", "Noto Sans", "Vamos construir!"),
    ("uk", "Ukrainian", "Noto Sans", "Будуймо!"),
    ("ur", "Urdu", "Noto Naskh Arabic", "آؤ بنائیں"),
]


def find_font(family):
    out = subprocess.check_output(["fc-match", "-f", "%{family[0]}\t%{file}\t%{index}", family], text=True)
    found, path, index = out.split("\t")
    if found != family:
        raise SystemExit(f"Font '{family}' not installed (fc-match returned '{found}')")
    # fontconfig packs the named-instance number into the high bits; Pillow wants the face index
    return path, int(index) & 0xFFFF


def render(text, family):
    path, index = find_font(family)
    font = ImageFont.truetype(path, SIZE_PX, index=index, layout_engine=ImageFont.Layout.RAQM)
    try:
        # Variable fonts default to their first instance (Thin for Noto CJK); use Regular everywhere
        font.set_variation_by_axes([WEIGHT if a["name"] in (b"Weight", "Weight") else a["default"]
                                    for a in font.get_variation_axes()])
    except OSError:
        pass  # static font
    left, top, right, bottom = font.getbbox(text)
    img = Image.new("L", (right - left + 2, bottom - top + 2), 0)
    ImageDraw.Draw(img).text((1 - left, 1 - top), text, font=font, fill=255)
    return img


def c_array(data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    return "\n".join(lines)


def main():
    if not features.check_feature("raqm"):
        raise SystemExit("Pillow was built without raqm; complex scripts would render incorrectly")

    header = "/* Generated by tools/gen_lang_images.py - do not edit */\n"
    src = [header, '#include "lang_images.h"\n']
    for ident, _, family, text in PHRASES:
        img = render(text, family)
        data = img.tobytes()
        src.append(f"/* {text} */")
        src.append(f"static const uint8_t img_{ident}_map[] = {{\n{c_array(data)}\n}};\n")
        src.append(f"static const lv_img_dsc_t img_{ident} = {{\n"
                   f"    .header.cf = LV_IMG_CF_ALPHA_8BIT,\n"
                   f"    .header.w = {img.width},\n"
                   f"    .header.h = {img.height},\n"
                   f"    .data_size = sizeof(img_{ident}_map),\n"
                   f"    .data = img_{ident}_map,\n}};\n")

    src.append("const lang_image_t lang_images[LANG_IMAGE_COUNT] = {")
    for ident, label, _, _ in PHRASES:
        src.append(f'    {{"{label}", &img_{ident}}},')
    src.append("};\n")

    hdr = [header, "#pragma once\n", '#include "lvgl.h"\n',
           f"#define LANG_IMAGE_COUNT {len(PHRASES)}\n",
           "typedef struct {",
           "    const char *language;      /* English name of the language */",
           "    const lv_img_dsc_t *img;   /* \"Let's build\" as an 8-bit alpha mask */",
           "} lang_image_t;\n",
           "extern const lang_image_t lang_images[LANG_IMAGE_COUNT];"]

    with open(os.path.join(OUT_DIR, "lang_images.c"), "w", encoding="utf-8") as f:
        f.write("\n".join(src))
    with open(os.path.join(OUT_DIR, "lang_images.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(hdr) + "\n")
    print(f"Wrote {len(PHRASES)} images to {OUT_DIR}")


if __name__ == "__main__":
    main()
